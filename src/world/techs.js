const PHASE_OF = (systems) => Math.max(0, ...systems.map((s) => SYSTEMS[s].phase));

/** Custo sugerido: a área principal cresce com a ordem; as secundárias pedem metade. */
function costOf(order, area, extraAreas, start) {
  const base = start ? 0 : Math.round((80 + (order - 1910) * 9) / 10) * 10;
  const cost = { [area]: base };
  for (const a of extraAreas) cost[a] = Math.round(base / 20) * 10;
  return cost;
}

const START = new Set(START_TECHS);

export const TECHS = TREE.map(([id, area, order, name, requires, extraAreas, desc, note]) => {
  const [kind, systems, mechanic] = MECHANICS[id];
  const sys = systems.split(' ').filter(Boolean);
  const phase = PHASE_OF(sys);
  const start = START.has(id);
  const effects = EFFECTS[id] ?? [];
  return {
    id, area, order, name, requires, extraAreas, desc, note, kind, mechanic,
    systems: sys,
    phase,
    marco: marcoAt(order).id,
    start,
    cost: costOf(order, area, extraAreas, start),
    effects,
    // Pode ser pesquisada nesta versão do jogo?
    ready: phase <= IMPLEMENTED_PHASE && (start || kind === 'Base' || id in EFFECTS),
  };
});

